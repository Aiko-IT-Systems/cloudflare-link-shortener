import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

const DEFAULT_LIMIT = 500;

function usage() {
	return `Usage:
  node scripts/prepare-play-release-notes.mjs --input <file|-> --output <file> [options]
  node scripts/prepare-play-release-notes.mjs --compose-only --output <file> [options]

Options:
  --operator-notes <text>       Extra operator-written notes
  --operator-notes-file <file> Repository-relative Markdown notes file
  --locale <locale>             Play locale (default: en-US)
  --limit <number>              Maximum note characters (default: 500)
  --compose-only                Write only the custom GitHub release body
`;
}

function parseArgs(argv) {
	const args = { locale: "en-US", limit: DEFAULT_LIMIT, composeOnly: false };
	for (let index = 0; index < argv.length; index += 1) {
		const argument = argv[index];
		if (argument === "--compose-only") {
			args.composeOnly = true;
			continue;
		}
		if (!argument.startsWith("--"))
			throw new Error(`Unexpected argument: ${argument}`);
		const key = argument.slice(2).replaceAll("-", "_");
		const value = argv[++index];
		if (!value || value.startsWith("--"))
			throw new Error(`Missing value for ${argument}`);
		if (key === "limit") {
			args.limit = Number(value);
			if (!Number.isInteger(args.limit) || args.limit < 1)
				throw new Error("--limit must be a positive integer.");
		} else if (key === "locale") args.locale = value;
		else if (key === "input") args.input = value;
		else if (key === "output") args.output = value;
		else if (key === "operator_notes") args.operatorNotes = value;
		else if (key === "operator_notes_file") args.operatorNotesFile = value;
		else throw new Error(`Unknown argument: ${argument}`);
	}
	if (!args.output) throw new Error("--output is required.");
	if (!args.composeOnly && !args.input)
		throw new Error("--input is required unless --compose-only is used.");
	if (!/^[A-Za-z0-9-]+$/.test(args.locale))
		throw new Error(
			"--locale must contain only letters, numbers, and hyphens.",
		);
	return args;
}

function assertSafeRepositoryPath(file, root = process.cwd()) {
	if (!file || file.includes("\0") || path.isAbsolute(file))
		throw new Error("Notes file must be a relative repository path.");
	const normalized = path.normalize(file);
	if (normalized === ".." || normalized.startsWith(`..${path.sep}`))
		throw new Error("Notes file must stay inside the repository.");
	const resolvedRoot = path.resolve(root);
	const resolved = path.resolve(resolvedRoot, normalized);
	if (
		resolved !== resolvedRoot &&
		!resolved.startsWith(`${resolvedRoot}${path.sep}`)
	)
		throw new Error("Notes file must stay inside the repository.");
	return resolved;
}

function rejectBinary(text, source) {
	if (
		text.includes("\0") ||
		(text.match(/[\u0001-\u0008\u000B\u000C\u000E-\u001F]/g)?.length ?? 0) >
			Math.max(2, text.length / 100)
	) {
		throw new Error(
			`${source} looks binary; refusing to include it in release notes.`,
		);
	}
}

async function readNotesFile(file, root = process.cwd()) {
	const resolved = assertSafeRepositoryPath(file, root);
	const text = await fs.readFile(resolved, "utf8");
	rejectBinary(text, file);
	return text;
}

export async function composeOperatorNotes({
	text = "",
	file,
	root = process.cwd(),
} = {}) {
	const parts = [];
	if (text.trim()) {
		rejectBinary(text, "operator notes");
		parts.push(text.trim());
	}
	if (file) {
		const fileText = (await readNotesFile(file, root)).trim();
		if (fileText) parts.push(fileText);
	}
	return parts.join("\n\n");
}

function stripMarkdownLine(line) {
	let result = line.trim();
	if (!result || /^<!--|-->$/.test(result)) return "";
	if (
		/^\s*[*_`]*\s*(full changelog|generated by|co-authored-by)\b/i.test(result)
	)
		return "";
	if (
		/\b(?:github_token|gh_token|authorization|access[_-]?token|refresh[_-]?token)\s*[:=]/i.test(
			result,
		) ||
		/\bsecrets\.[A-Z0-9_]+\b|\bgithub\.event\./i.test(result)
	)
		return "";
	result = result.replace(/^#{1,6}\s+/, "");
	result = result.replace(/^[-*+]\s+/, "• ");
	result = result.replace(/^\d+[.)]\s+/, "• ");
	result = result.replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1");
	result = result.replace(/\[([^\]]+)\]\([^)]*\)/g, "$1");
	result = result.replace(/<https?:\/\/[^>]+>/g, "");
	result = result.replace(/`([^`]*)`/g, "$1");
	result = result.replace(/<[^>]+>/g, "");
	result = result.replace(/\s+/g, " ").trim();
	return result;
}

export function normalizePlayNotes(
	markdown,
	{ operatorNotes = "", limit = DEFAULT_LIMIT, locale = "en-US" } = {},
) {
	rejectBinary(markdown, "release body");
	const lines = markdown.replaceAll("\r\n", "\n").split("\n");
	const kept = [];
	let skippingContributors = false;
	for (const line of lines) {
		const heading = line.replace(/^\s*#+\s*/, "").trim();
		if (/^(?:new )?contributors?$/i.test(heading)) {
			skippingContributors = true;
			continue;
		}
		if (
			/^(generated by|automated changes?|what(?:'|’)s changed|changes in release)$/i.test(
				heading,
			)
		)
			continue;
		if (skippingContributors && /^#+\s+/.test(line))
			skippingContributors = false;
		if (skippingContributors) continue;
		const cleaned = stripMarkdownLine(line);
		if (cleaned && !kept.includes(cleaned)) kept.push(cleaned);
	}
	const custom = operatorNotes
		? operatorNotes
				.split("\n")
				.map(stripMarkdownLine)
				.filter(Boolean)
				.join("\n")
				.trim()
		: "";
	const content = [custom, ...kept]
		.filter(Boolean)
		.join("\n")
		.replace(/\n{2,}/g, "\n")
		.trim();
	if (!content) throw new Error("Release notes are empty after conversion.");
	const characters = Array.from(content);
	let limited = characters.slice(0, limit).join("");
	if (characters.length > limit) {
		if (limit === 1) limited = "…";
		else {
			limited = characters.slice(0, limit - 1).join("");
			const boundary = limited.lastIndexOf(" ");
			if (boundary >= Math.floor((limit - 1) * 0.65))
				limited = limited.slice(0, boundary);
			limited = `${limited.trimEnd()}…`;
		}
	}
	return `<${locale}>\n${limited}\n</${locale}>`;
}

async function main() {
	const args = parseArgs(process.argv.slice(2));
	const operatorNotes = await composeOperatorNotes({
		text: args.operatorNotes,
		file: args.operatorNotesFile,
	});
	if (args.composeOnly) {
		await fs.mkdir(path.dirname(path.resolve(args.output)), {
			recursive: true,
		});
		await fs.writeFile(args.output, operatorNotes, "utf8");
		console.log(
			JSON.stringify({
				output: args.output,
				sourceCharacters: Array.from(operatorNotes).length,
			}),
		);
		return;
	}
	const input =
		args.input === "-"
			? await new Promise((resolve, reject) => {
					let value = "";
					process.stdin.setEncoding("utf8");
					process.stdin.on("data", (chunk) => {
						value += chunk;
					});
					process.stdin.on("end", () => resolve(value));
					process.stdin.on("error", reject);
				})
			: await fs.readFile(args.input, "utf8");
	const output = normalizePlayNotes(input, {
		operatorNotes,
		limit: args.limit,
		locale: args.locale,
	});
	await fs.mkdir(path.dirname(path.resolve(args.output)), { recursive: true });
	await fs.writeFile(args.output, output, "utf8");
	console.log(
		JSON.stringify({
			output: args.output,
			sourceCharacters: Array.from(output).length,
			playCharacters: Array.from(output.split("\n")[1] ?? "").length,
		}),
	);
}

if (
	process.argv[1] &&
	import.meta.url === pathToFileURL(process.argv[1]).href
) {
	main().catch((error) => {
		console.error(`Release notes error: ${error.message}`);
		process.exitCode = 1;
	});
}
